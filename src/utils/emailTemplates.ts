export function isValidEmailTemplateKey(value: string): value is EmailTemplateKey {
  return (EMAIL_TEMPLATE_KEYS as readonly string[]).includes(value);
}

export function sanitizeEmailHeaderColor(color: unknown, fallback = '#059669'): string {
  const safeFallback = /^#[0-9a-f]{6}$/i.test(fallback) ? fallback.toLowerCase() : '#059669';
  if (typeof color !== 'string') return safeFallback;
  const trimmed = color.trim();
  if (/^#[0-9a-f]{6}$/i.test(trimmed)) {
    return trimmed.toLowerCase();
  }
  return safeFallback;
}

export function darkenHexColor(hex: string, factor = 0.24): string {
  const safe = sanitizeEmailHeaderColor(hex);
  const r = parseInt(safe.slice(1, 3), 16);
  const g = parseInt(safe.slice(3, 5), 16);
  const b = parseInt(safe.slice(5, 7), 16);
  const clamp = (n: number) => Math.max(0, Math.min(255, Math.round(n)));
  const dr = clamp(r * (1 - factor)).toString(16).padStart(2, '0');
  const dg = clamp(g * (1 - factor)).toString(16).padStart(2, '0');
  const db = clamp(b * (1 - factor)).toString(16).padStart(2, '0');
  return `#${dr}${dg}${db}`;
}

export function resolveEmailTemplate(
  key: EmailTemplateKey,
  overrides?: EmailTemplateCollection | null
): EmailTemplateFormat {
  const def = DEFAULT_EMAIL_TEMPLATES[key];
  const custom = overrides?.[key];
  if (!custom) return { ...def };

  const subject =
    typeof custom.subject === 'string' && custom.subject.trim()
      ? custom.subject.trim().slice(0, 220)
      : def.subject;
  const greeting =
    typeof custom.greeting === 'string' && custom.greeting.trim()
      ? custom.greeting.trim().slice(0, 220)
      : def.greeting;
  const introBody =
    typeof custom.introBody === 'string' && custom.introBody.trim()
      ? custom.introBody.trim().slice(0, 2000)
      : def.introBody;
  const footerNote =
    typeof custom.footerNote === 'string'
      ? custom.footerNote.trim().slice(0, 1000)
      : def.footerNote;
  const headerColor = sanitizeEmailHeaderColor(custom.headerColor, def.headerColor);

  return {
    subject,
    greeting,
    introBody,
    footerNote,
    headerColor,
  };
}

export function interpolateTemplateString(
  templateText: string,
  vars: Record<string, string | number | undefined | null>
): string {
  return templateText.replace(/\{\{\s*([a-zA-Z0-9_]+)\s*\}\}/g, (_match, rawKey: string) => {
    const val = vars[rawKey];
    if (val === undefined || val === null) return '';
    return String(val);
  });
}

export function interpolateEmailTemplate(
  template: EmailTemplateFormat,
  vars: Record<string, string | number | undefined | null>
): EmailTemplateFormat {
  return {
    subject: interpolateTemplateString(template.subject, vars).trim(),
    greeting: interpolateTemplateString(template.greeting, vars).trim(),
    introBody: interpolateTemplateString(template.introBody, vars).trim(),
    footerNote: interpolateTemplateString(template.footerNote, vars).trim(),
    headerColor: sanitizeEmailHeaderColor(template.headerColor),
  };
}

export function buildSampleTemplateVars(
  key: EmailTemplateKey,
  fundName?: string,
  currency?: string
): Record<string, string> {
  const vars: Record<string, string> = {};
  for (const v of EMAIL_TEMPLATE_META[key].variables) {
    vars[v.key] = v.sample;
  }
  if (fundName && fundName.trim()) {
    vars.fundName = fundName.trim();
  }
  if (currency && currency.trim()) {
    vars.currency = currency.trim();
    if (vars.amount) {
      vars.amount = `5,000 ${currency.trim()}`;
    }
    if (vars.amanahHeight) vars.amanahHeight = `485,000 ${currency.trim()}`;
    if (vars.currentBalance) vars.currentBalance = `390,000 ${currency.trim()}`;
    if (vars.monthlyCollected) vars.monthlyCollected = `65,000 ${currency.trim()}`;
    if (vars.activeLoanTotal) vars.activeLoanTotal = `95,000 ${currency.trim()}`;
  }
  return vars;
}

export function sanitizeSingleEmailTemplateFormat(
  key: EmailTemplateKey,
  input: unknown
): Partial<EmailTemplateFormat> | null {
  if (!input || typeof input !== 'object') return null;
  const raw = input as Record<string, unknown>;
  const def = DEFAULT_EMAIL_TEMPLATES[key];
  const clean: Partial<EmailTemplateFormat> = {};

  if (typeof raw.subject === 'string') {
    const s = raw.subject.trim().slice(0, 220);
    if (s && s !== def.subject) clean.subject = s;
  }
  if (typeof raw.greeting === 'string') {
    const g = raw.greeting.trim().slice(0, 220);
    if (g && g !== def.greeting) clean.greeting = g;
  }
  if (typeof raw.introBody === 'string') {
    const b = raw.introBody.trim().slice(0, 2000);
    if (b && b !== def.introBody) clean.introBody = b;
  }
  if (typeof raw.footerNote === 'string') {
    const f = raw.footerNote.trim().slice(0, 1000);
    if (f !== def.footerNote) clean.footerNote = f;
  }
  if (typeof raw.headerColor === 'string') {
    const c = sanitizeEmailHeaderColor(raw.headerColor, def.headerColor);
    if (c !== def.headerColor) clean.headerColor = c;
  }

  return Object.keys(clean).length > 0 ? clean : null;
}

export function mergeEmailTemplateCollections(
  existing: EmailTemplateCollection | undefined,
  incoming: unknown
): EmailTemplateCollection | undefined {
  if (incoming === null) return undefined;
  if (!incoming || typeof incoming !== 'object') return existing;

  const rawMap = incoming as Record<string, unknown>;
  const next: EmailTemplateCollection = { ...(existing || {}) };

  for (const key of EMAIL_TEMPLATE_KEYS) {
    if (!(key in rawMap)) continue;
    const entry = rawMap[key];
    if (entry === null) {
      delete next[key];
      continue;
    }
    const mergedRaw = {
      ...resolveEmailTemplate(key, existing),
      ...(typeof entry === 'object' && entry ? (entry as Record<string, unknown>) : {}),
    };
    const cleaned = sanitizeSingleEmailTemplateFormat(key, mergedRaw);
    if (cleaned) {
      next[key] = cleaned;
    } else {
      delete next[key];
    }
  }

  return Object.keys(next).length > 0 ? next : undefined;
}
